SELECT 
GERE.STR_COD_AREA AS AREA,
GERE.STR_DIM_CHG_NUM_CHEQUE_GER_NK AS CHG_NUM_CHQ_GER,
GERE.STR_PRIMER_BENEFICIARIO AS CHG_PRIMER_BENEFICIARIO,
GERE.STR_TIPO_DOCUMENTO_PRIMERO AS CHG_TIPO_DOC_PRIMER,
GERE.STR_NUM_IDENTIFICACION_PRIMERO AS CHG_NUM_ID_PRIMER,
CASE WHEN STR_SEGUNDO_BENEFICIARIO = '-' THEN NULL ELSE STR_SEGUNDO_BENEFICIARIO END SEGUNDO_BENEFICIARIO,
CASE WHEN STR_TIPO_DOCUMENTO_SEGUNDO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_SEGUNDO END TIPO_DOCUMENTO_SEGUNDO,
CASE WHEN STR_NUM_IDENTIFICACION_SEGUNDO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_SEGUNDO END NUM_IDENTIFICACION_SEGUNDO,
CASE WHEN STR_TERCER_BENEFICIARIO = '-' THEN NULL ELSE STR_TERCER_BENEFICIARIO END TERCER_BENEFICIARIO,
CASE WHEN STR_TIPO_DOCUMENTO_TERCERO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_TERCERO END TIPO_DOCUMENTO_TERCERO,
CASE WHEN STR_NUM_IDENTIFICACION_TERCERO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_TERCERO END IDENTIFICACION_TERCERO,
CASE WHEN STR_CONJUNCION = '-' THEN NULL ELSE STR_CONJUNCION END CONJUNCION,
GERE.STR_ESTADO_CHEQUE AS CHG_ESTADO_CHQ,
GERE.DTM_FCHA_EXPEDICION AS CHG_FECHA_EXPED_CHQ,
GERE.NUM_VALOR AS CHG_VALOR_TRANS,
OFI.STR_DIM_OFI_REGION_NK AS OFI_COD_REGION,
OFI.STR_NOMBRE_REGION AS OFI_NOM_REGION,
OFI.STR_NOMBRE_OFICINA AS OFI_NOM_OFICINA,
STR_DIM_CHG_COD_OFICINA_NK AS OFI_COD_OFICINA
FROM ADMODS.DIM_CHEQUE_GERENCIA GERE, ADMODS.DIM_OFICINA OFI
WHERE GERE.STR_DIM_CHG_COD_OFICINA_NK=OFI.STR_DIM_OFI_OFICINA_NK
AND STR_DIM_CHG_COD_ESTADO_NK = 'INIT'
AND STR_DIM_CHG_COD_OFICINA_NK LIKE  :P_OFICINA
AND OFI.STR_NOMBRE_REGION IN (:P_REGIONAL)
ORDER BY STR_DIM_CHG_COD_OFICINA_NK,
STR_DIM_CHG_NUM_CHEQUE_GER_NK