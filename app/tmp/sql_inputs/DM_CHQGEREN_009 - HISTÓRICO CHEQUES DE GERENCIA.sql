SELECT  
    "CHEQUE GERENCIA"."DIM CHG CODIGO OFICINA NK" AS "DIM CHG CODIGO OFICINA NK", 
    "OFICINA"."DIM OFI OFICINA NK" AS "DIM OFI OFICINA NK",            
       "TIEMPO FCHA TRANSAC"."DIM TIE DIA NK" AS "DIM TIE DIA NK", 
    "CHEQUE GERENCIA"."DIM CHG NUMERO CHEQUE GER NK" AS "DIM CHG NUMERO CHEQUE GER NK", 
    "CHEQUE GERENCIA"."ESTADO CHEQUE" AS "ESTADO CHEQUE", 
    "CHEQUE GERENCIA"."UBICACION CHEQUE" AS "UBICACION CHEQUE", 
    "CHEQUE GERENCIA"."VALOR" AS "VALOR", 
    "CHEQUE GERENCIA"."PRIMER BENEFICIARIO" AS "PRIMER BENEFICIARIO",
    "CHEQUE GERENCIA"."IDENTIFICACION PRIMERO" AS "IDENTIFICACION PRIMERO",
    "F CHEQUES GERENCIA"."COD USUARIO GENERA TRX" AS "COD USUARIO GENERA TRX", 
    "F CHEQUES GERENCIA"."OBSERVACIONES" AS "OBSERVACIONES",
    "OFICINA"."NOMBRE REGION" AS "NOMBRE REGION",
    "OFICINA"."NOMBRE OFICINA" AS "NOMBRE OFICINA",
    "OFICINA"."DIM OFI REGION NK" AS "DIM OFI REGION NK"   
FROM 
    "CBS - CHEQUES_GERENCIA"."OFICINA" "OFICINA",
    "CBS - CHEQUES_GERENCIA"."TIEMPO FCHA TRANSAC" "TIEMPO FCHA TRANSAC", 
    "CBS - CHEQUES_GERENCIA"."F CHEQUES GERENCIA" "F CHEQUES GERENCIA", 
    "CBS - CHEQUES_GERENCIA"."CHEQUE GERENCIA" "CHEQUE GERENCIA",
    "CBS - CHEQUES_GERENCIA"."ESTADO" "ESTADO"    

    
 WHERE        "CHEQUE GERENCIA"."DIM CHEQUE GERENCIA SK"="F CHEQUES GERENCIA"."DIM CHEQUE GERENCIA SK" AND
    "F CHEQUES GERENCIA"."DIM ESTADO SK"="ESTADO"."DIM ESTADO SK" AND
    "F CHEQUES GERENCIA"."DIM TIE FECHA TRANSAC SK"="TIEMPO FCHA TRANSAC"."DIM TIEMPO SK" AND
    "F CHEQUES GERENCIA"."DIM OFICINA SK"="OFICINA"."DIM OFICINA SK" AND    
       "TIEMPO FCHA TRANSAC"."DIM TIE DIA NK" >= :P_FECHA_DESDE AND
    "TIEMPO FCHA TRANSAC"."DIM TIE DIA NK" <= :P_FECHA_HASTA AND    
    "CHEQUE GERENCIA"."DIM CHG CODIGO OFICINA NK" IN (:P_OFICINA) AND
    "CHEQUE GERENCIA"."DIM CHG NUMERO CHEQUE GER NK" LIKE :P_CHEQUE AND
                "CHEQUE GERENCIA"."VALOR" LIKE :P_VALOR 

ORDER BY 
    "CHEQUE GERENCIA"."DIM CHG CODIGO OFICINA NK" ASC,
    "OFICINA"."DIM OFI OFICINA NK" ASC,
    --"TIEMPO FCHA TRANSAC"."DIM TIE DIA NK" ASC,
    "CHEQUE GERENCIA"."DIM CHG NUMERO CHEQUE GER NK" ASC