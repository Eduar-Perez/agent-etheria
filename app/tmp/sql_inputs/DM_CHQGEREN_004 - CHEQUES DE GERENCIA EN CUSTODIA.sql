TIMESTAMPDIFF(SQL_TSI_DAY, "CHEQUE GERENCIA"."FECHA EXPEDICION",CURRENT_DATE) AS "DURACION",
  "CHEQUE GERENCIA"."DIM CHG NUMERO CHEQUE GER NK" AS "DIM CHG NUMERO CHEQUE GER NK",
  "CHEQUE GERENCIA"."PRIMER BENEFICIARIO" AS "PRIMER BENEFICIARIO",
  "CHEQUE GERENCIA"."TIPO DOCUMENTO PRIMERO" AS "TIPO DOCUMENTO PRIMERO",
  "CHEQUE GERENCIA"."IDENTIFICACION PRIMERO" AS "IDENTIFICACION PRIMERO",
  "CHEQUE GERENCIA"."SEGUNDO BENEFICIARIO" AS "SEGUNDO BENEFICIARIO",
  "CHEQUE GERENCIA"."TIPO DOCUMENTO SEGUNDO" AS "TIPO DOCUMENTO SEGUNDO",
  "CHEQUE GERENCIA"."IDENTIFICACION SEGUNDO" AS "IDENTIFICACION SEGUNDO",
  "CHEQUE GERENCIA"."TERCER BENEFICIARIO" AS "TERCER BENEFICIARIO",
  "CHEQUE GERENCIA"."TIPO DOCUMENTO TERCERO" AS "TIPO DOCUMENTO TERCERO",
  "CHEQUE GERENCIA"."IDENTIFICACION TERCERO" AS "IDENTIFICACION TERCERO",
  "CHEQUE GERENCIA"."CONJUNCION" AS "CONJUNCION",
  "CHEQUE GERENCIA"."FECHA EXPEDICION" AS "FECHA EXPEDICION",
  "CHEQUE GERENCIA"."VALOR" AS "VALOR",
  "CHEQUE GERENCIA"."UBICACION CHEQUE" AS "UBICACION CHEQUE",
  "CHEQUE GERENCIA"."ESTADO CHEQUE" AS "ESTADO CHEQUE",
  "F CHEQUES GERENCIA"."DIM OFICINA SK" AS "DIM OFICINA SK",
  "OFICINA"."DIM OFI OFICINA NK" AS "DIM OFI OFICINA NK",
  "OFICINA"."DIM OFI REGION NK" AS "DIM OFI REGION NK",
   "OFICINA"."NOMBRE OFICINA" AS "NOMBRE OFICINA",
  "OFICINA"."NOMBRE REGION" AS "NOMBRE REGION"
 FROM "CBS - CHEQUES_GERENCIA"."CHEQUE GERENCIA" "CHEQUE GERENCIA",
"CBS - CHEQUES_GERENCIA"."OFICINA" "OFICINA",
 "CBS - CHEQUES_GERENCIA"."F CHEQUES GERENCIA" "F CHEQUES GERENCIA"
WHERE 
"OFICINA"."DIM OFI OFICINA NK" IN (:P_OFICINA) AND
"OFICINA"."DIM OFI REGION NK" IN (:P_REGION) AND
"CHEQUE GERENCIA"."UBICACION CHEQUE" = 'EN PODER DEL BANCO' AND
"CHEQUE GERENCIA"."ESTADO CHEQUE" = 'ACTIVO' AND
TIMESTAMPDIFF(SQL_TSI_DAY, "CHEQUE GERENCIA"."FECHA EXPEDICION",CURRENT_DATE) > 45 
AND TIMESTAMPDIFF(SQL_TSI_DAY, "CHEQUE GERENCIA"."FECHA EXPEDICION",CURRENT_DATE) < 180