SELECT DISTINCT GERE.STR_DIM_CHG_NUM_CHEQUE_GER_NK AS CHG_NUM_CHQ_GER, 
                GERE.STR_COD_AREA AS COD_AREA, 
                MAX(T.DTM_DIM_TIE_DIA_NK) AS FECHA_TRANSACCION,
              GERE.STR_PRIMER_BENEFICIARIO AS CHG_PRIMER_BENEFICIARIO,
GERE.STR_TIPO_DOCUMENTO_PRIMERO AS CHG_TIPO_DOC_PRIMER,
GERE.STR_NUM_IDENTIFICACION_PRIMERO AS CHG_NUM_ID_PRIMER,

CASE WHEN STR_SEGUNDO_BENEFICIARIO = '-' THEN NULL ELSE STR_SEGUNDO_BENEFICIARIO END SEGUNDO_BENEFICIARIO,
CASE WHEN STR_TIPO_DOCUMENTO_SEGUNDO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_SEGUNDO END TIPO_DOCUMENTO_SEGUNDO,
CASE WHEN STR_NUM_IDENTIFICACION_SEGUNDO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_SEGUNDO END NUM_IDENTIFICACION_SEGUNDO,
CASE WHEN STR_TERCER_BENEFICIARIO = '-' THEN NULL ELSE STR_TERCER_BENEFICIARIO END TERCER_BENEFICIARIO,
CASE WHEN STR_TIPO_DOCUMENTO_TERCERO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_TERCERO END TIPO_DOCUMENTO_TERCERO,
CASE WHEN STR_NUM_IDENTIFICACION_TERCERO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_TERCERO END IDENTIFICACION_TERCERO,
CASE WHEN STR_CONJUNCION = '-' THEN NULL ELSE STR_CONJUNCION END CONJUNCION,

GERE.STR_ESTADO_CHEQUE AS CHG_ESTADO_CHQ,
GERE.DTM_FCHA_EXPEDICION AS CHG_FECHA_EXPED_CHQ,
GERE.NUM_VALOR AS CHG_VALOR_TRANS,
OFI.STR_DIM_OFI_REGION_NK AS OFI_COD_REGION,
OFI.STR_NOMBRE_REGION AS OFI_NOM_REGION,
OFI.STR_NOMBRE_OFICINA AS OFI_NOM_OFICINA,
TRUNC(SYSDATE - GERE.DTM_FCHA_EXPEDICION) AS DIAS_ACUM
FROM ADMODS.FCT_CHEQUES_GERENCIA FCT, 
ADMODS.DIM_CHEQUE_GERENCIA GERE, 
ADMODS.DIM_TIEMPO T,
ADMODS.DIM_OFICINA OFI

WHERE FCT.NUM_DIM_CHEQUE_GERENCIA_SK=GERE.NUM_DIM_CHEQUE_GERENCIA_SK
AND FCT.NUM_DIM_TIE_FCHA_TRANSAC_SK=T.NUM_DIM_TIEMPO_SK
AND FCT.NUM_DIM_OFICINA_SK=OFI.NUM_DIM_OFICINA_SK
AND T.DTM_DIM_TIE_DIA_NK >= :P_FECHA_DESDE  AND T.DTM_DIM_TIE_DIA_NK <= :P_FECHA_HASTA  AND GERE.STR_DIM_CHG_COD_ESTADO_NK = 'INAV'
AND GERE.STR_DIM_CHG_COD_OFICINA_NK IN (:P_OFICINA)
GROUP BY GERE.STR_DIM_CHG_NUM_CHEQUE_GER_NK,
GERE.STR_COD_AREA,
GERE.STR_PRIMER_BENEFICIARIO,
GERE.STR_TIPO_DOCUMENTO_PRIMERO,
GERE.STR_NUM_IDENTIFICACION_PRIMERO,
CASE WHEN STR_SEGUNDO_BENEFICIARIO = '-' THEN NULL ELSE STR_SEGUNDO_BENEFICIARIO END,
CASE WHEN STR_TIPO_DOCUMENTO_SEGUNDO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_SEGUNDO END,
CASE WHEN STR_NUM_IDENTIFICACION_SEGUNDO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_SEGUNDO END,
CASE WHEN STR_TERCER_BENEFICIARIO = '-' THEN NULL ELSE STR_TERCER_BENEFICIARIO END,
CASE WHEN STR_TIPO_DOCUMENTO_TERCERO = '-' THEN NULL ELSE STR_TIPO_DOCUMENTO_TERCERO END,
CASE WHEN STR_NUM_IDENTIFICACION_TERCERO = '-' THEN NULL ELSE STR_NUM_IDENTIFICACION_TERCERO END,
CASE WHEN STR_CONJUNCION = '-' THEN NULL ELSE STR_CONJUNCION END,
GERE.STR_ESTADO_CHEQUE,
GERE.DTM_FCHA_EXPEDICION,
GERE.NUM_VALOR,
OFI.STR_DIM_OFI_REGION_NK,
OFI.STR_NOMBRE_REGION,
OFI.STR_NOMBRE_OFICINA,
TRUNC(SYSDATE - GERE.DTM_FCHA_EXPEDICION)
ORDER BY GERE.STR_DIM_CHG_NUM_CHEQUE_GER_NK